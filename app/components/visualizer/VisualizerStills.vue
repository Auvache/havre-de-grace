<template>
  <div class="space-y-14">
    <section v-for="idea in ideas" :id="idea.id" :key="idea.id" class="scroll-mt-8 space-y-4">
      <h2 class="section-heading text-[1.35rem]">
        {{ idea.name }}
      </h2>
      <div class="grid gap-3 sm:grid-cols-2">
        <figure v-for="still in idea.stills" :key="still.src" class="min-w-0 space-y-2">
          <VisualizerStill :src="still.src" />
          <figcaption class="font-mono text-xs muted-text">
            {{ clock(still.time) }}
          </figcaption>
        </figure>
      </div>
    </section>
  </div>
</template>

<script setup lang="ts">
/*
 * A song with no film yet: its proposed visualizers as stills, nothing else.
 * The stills and this list are generated by
 * `SITE=1 node tools/video-styles/visualizers/build.mjs`; what each idea is
 * lives in docs/visualizers/<song>.md.
 */
import type { ProposedVisualizer } from '~/config/visualizerStills'

defineProps<{ ideas: ProposedVisualizer[] }>()

const clock = (s: number) => `${Math.floor(s / 60)}:${String(Math.floor(s % 60)).padStart(2, '0')}`
</script>
